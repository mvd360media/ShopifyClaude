import { chromium } from 'playwright';
const [,, url, out, foto] = process.argv;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell', args: ['--no-sandbox'] });
const p = await b.newPage({ viewport: { width: 1366, height: 900 } });
await p.goto(url, { waitUntil: 'load', timeout: 90000 }); await p.waitForTimeout(2000);
await p.evaluate(() => document.querySelectorAll('#shopify-pc__banner, .shopify-pc__banner__dialog').forEach(e => e.remove()));
const f = p.locator('[data-oc-pers] input[type=file]'); if (await f.count()) await f.setInputFiles(foto);
const t = p.locator('[data-oc-pers] input[type=text]'); for (let i = 0; i < await t.count(); i++) await t.nth(i).fill('Lila');
const s = p.locator('[data-oc-pers] select'); if (await s.count()) await s.selectOption({ index: 1 });
await p.locator('[data-oc-confirmacion]').check();
await p.click('.oc-compra__boton'); await p.waitForTimeout(4000);
console.log('url:', p.url().slice(0, 70), '| ventana abierta:', await p.evaluate(() => !!document.querySelector('[data-oc-emergente]')?.open));
console.log('en la ventana:', (await p.evaluate(() => document.querySelector('[data-oc-emergente-producto]')?.innerText || '')).replace(/\s+/g, ' '), '| sugerencias:', await p.locator('.oc-emergente__sugerencias .oc-card').count());
console.log('burbuja carrito:', await p.evaluate(() => document.getElementById('cart-icon-bubble')?.innerText.replace(/\s+/g,' ').trim()));
await p.screenshot({ path: out + '-1.png' });
const cart = await p.evaluate(async () => (await (await fetch('/cart.js')).json()).items.map(i => ({ t: i.product_title, props: i.properties })));
console.log('carrito:', JSON.stringify(cart).slice(0, 500));
await p.goto(url.split('/products/')[0] + '/cart', { waitUntil: 'load' }); await p.waitForTimeout(2500);
console.log('sugerencias visibles en el carrito:', await p.evaluate(() => [...document.querySelectorAll('.oc-complementos .oc-card')].filter(c => getComputedStyle(c).opacity === '1').length));
await p.evaluate(() => document.querySelector('.oc-complementos')?.scrollIntoView()); await p.waitForTimeout(1200);
await p.screenshot({ path: out + '-2.png' });
await p.evaluate(async () => { await fetch('/cart/clear.js', { method: 'POST' }); });
await b.close();
